import { bfsGenerated, costDepth, idsGenerated } from "@/lib/widgets/ai-lecture-03";
import { checkCostExpect, costFacts, costInputError, costRows, type CostInputs } from "@/lib/widgets/cheat-ai";
import { WidgetShell } from "./WidgetShell";
import { bi } from "./types";
import { SearchCostCalcPlayer } from "./players";

const where = "<SearchCostCalc>";

/**
 * The counts must agree with Lecture 3's own (lib/widgets/ai-lecture-03.ts), exactly, wherever
 * those fit in a double; and with the page's worked numbers.
 */
function crossCheck(input: CostInputs) {
  const { b, d } = input;
  const root = input.root ?? false;
  if (b ** (d + 1) <= Number.MAX_SAFE_INTEGER) {
    const facts = costFacts(input);
    const lecture = {
      ids: idsGenerated(b, d, root),
      "bfs-gen": bfsGenerated(b, d, "generation", root),
      "bfs-exp": bfsGenerated(b, d, "expansion", root),
    };
    for (const [key, value] of Object.entries(lecture)) {
      if (facts[key as keyof typeof lecture] !== BigInt(value)) throw new Error(`${where}: ${key} disagrees with ai-lecture-03 for b=${b} d=${d}`);
    }
  }
  const ucs = costRows(input).find((r) => r.key === "ucs")?.ucs;
  if (ucs && Number.isInteger(input.cstar) && Number.isInteger(input.eps) && ucs.ceil !== costDepth(input.cstar!, input.eps!)) {
    throw new Error(`${where}: ⌈C*/ε⌉ disagrees with ai-lecture-03's costDepth`);
  }
}

// Lecture 3's worked numbers: b = 10, d = 5 without the root, and its b = 2 practice with it.
const LECTURE_FACTS = "b=10 d=5 => ids=123450; bfs-exp=1111100; bfs-gen=111110 | b=2 d=3 root => ids=26; bfs-gen=15";
const selfTest = checkCostExpect(LECTURE_FACTS, { b: 10, d: 5 });
if (selfTest.length) throw new Error(`${where}: the counts disagree with Lecture 3:\n  ${selfTest.join("\n  ")}`);

/**
 * <SearchCostCalc b={10} d={5} m={7} l={3} cstar={418} eps={80}
 *   expect="b=10 d=5 => ids=123450; bfs-gen=111110; bfs-exp=1111100" />
 *
 * Worst-case nodes generated by BFS (goal tested on generation and on expansion), IDS, DFS to
 * depth m, DLS to limit l, UCS (b^(1+⌊C* ÷ ε⌋)) and bidirectional search, with each series written
 * out, the Big-O bounds, the geometric-series shortcut and the IDS/BFS ratio. Every input can be
 * edited in the widget; m, l, C* and ε are optional (their rows wait for them). The root is left
 * out of the counts, as in Lecture 3's b = 10 example, unless `root` is set (its b = 2 practice).
 *
 * `expect`, copied from the page, makes the build fail if the calculator disagrees: clauses
 * separated by "|", each `[inputs] => key=number; …`. The inputs (b=, d=, m=, l=, cstar=, eps=,
 * root) override the props; keys are bfs-gen, bfs-exp, ids, dfs, dls, ucs, bidi and ratio
 * (IDS ÷ BFS on generation). Full grammar: checkCostExpect in lib/widgets/cheat-ai.ts.
 */
export function SearchCostCalc({
  b = 10,
  d = 5,
  m,
  l,
  cstar,
  eps,
  root = false,
  expect,
  title = "How many nodes? Worst-case counts from b and d",
  titleAr = "كم عقدة؟ أعداد أسوأ الحالات بدلالة b\u00a0و\u00a0d",
  caption,
  captionAr,
}: {
  b?: number;
  d?: number;
  m?: number;
  l?: number;
  cstar?: number;
  eps?: number;
  root?: boolean;
  expect?: string;
  title?: string;
  titleAr?: string;
  caption?: string;
  captionAr?: string;
}) {
  const input: CostInputs = { b, d, m: m ?? null, l: l ?? null, cstar: cstar ?? null, eps: eps ?? null, root };
  const problem = costInputError(input);
  if (problem) throw new Error(`${where}: ${problem}`);
  crossCheck(input);

  if (expect) {
    const failures = checkCostExpect(expect, input);
    if (failures.length) throw new Error(`${where} expect does not hold:\n  ${failures.join("\n  ")}`);
  }

  return (
    <WidgetShell
      name="search-cost-calc"
      kicker={bi("Calculator", "حاسبة")}
      title={title}
      titleAr={titleAr}
      caption={caption}
      captionAr={captionAr}
    >
      <SearchCostCalcPlayer b={b} d={d} m={input.m ?? null} l={input.l ?? null} cstar={input.cstar ?? null} eps={input.eps ?? null} root={root} />
    </WidgetShell>
  );
}
